                         start_date, end_date, price, image_url)
SELECT d.title, d.description, c.id, ci.id, d.address, d.lat, d.lng,
       fn_today() + d.start_off, fn_today() + d.end_off, d.price, d.image_url
FROM demo d
JOIN categories c  ON lower(c.name)  = lower(d.category_name)
JOIN cities     ci ON lower(ci.name) = lower(d.city_name)
